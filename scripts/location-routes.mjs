// Regenerates src/content/location-routes.ts: the driving route from each nearby place
// (src/content/location.ts) to the compound (site.coordinates), from the public OSRM router.
// Run after adding or moving a place:  node scripts/location-routes.mjs
// The routes are stored in the site, so the live map never depends on the router.
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const read = (p) => readFileSync(new URL(p, root), "utf8");

const site = read("src/content/site.ts").match(/coordinates: \{ lat: ([\d.]+), lng: ([\d.]+) \}/);
const project = { lat: +site[1], lng: +site[2] };
const places = [...read("src/content/location.ts").matchAll(/id: "([\w-]+)".*?coords: \{ lat: ([\d.]+), lng: ([\d.]+) \}/g)].map(
  ([, id, lat, lng]) => ({ id, lat: +lat, lng: +lng }),
);

/** Douglas–Peucker in degrees; ~0.00006° ≈ 6 m keeps every bend that shows on the map. */
function simplify(pts, tol = 0.00006) {
  if (pts.length < 3) return pts;
  const [a, b] = [pts[0], pts.at(-1)];
  let max = 0;
  let at = 0;
  for (let i = 1; i < pts.length - 1; i++) {
    const [y, x] = pts[i];
    const dx = b[1] - a[1];
    const dy = b[0] - a[0];
    const d = Math.abs(dy * x - dx * y + b[1] * a[0] - b[0] * a[1]) / (Math.hypot(dx, dy) || 1);
    if (d > max) [max, at] = [d, i];
  }
  if (max <= tol) return [a, b];
  return [...simplify(pts.slice(0, at + 1), tol).slice(0, -1), ...simplify(pts.slice(at), tol)];
}

const routes = {};
for (const p of places) {
  const url = `https://router.project-osrm.org/route/v1/driving/${p.lng},${p.lat};${project.lng},${project.lat}?overview=full&geometries=geojson`;
  const data = await (await fetch(url)).json();
  const coords = data?.routes?.[0]?.geometry?.coordinates;
  if (!coords) throw new Error(`No route for ${p.id}: ${JSON.stringify(data).slice(0, 200)}`);
  const pts = simplify(coords.map(([lng, lat]) => [+lat.toFixed(5), +lng.toFixed(5)]));
  routes[p.id] = pts;
  console.log(`${p.id}: ${(data.routes[0].distance / 1000).toFixed(1)} km, ${coords.length} → ${pts.length} points`);
}

const body = Object.entries(routes)
  .map(([id, pts]) => `  "${id}": [${pts.map(([lat, lng]) => `[${lat},${lng}]`).join(",")}],`)
  .join("\n");

writeFileSync(
  new URL("src/content/location-routes.ts", root),
  `// Generated by scripts/location-routes.mjs: do not edit by hand.
// Driving route from each nearby place to the compound, as [lat, lng], place first.
export const placeRoutes: Record<string, [number, number][]> = {
${body}
};
`,
);
