// Writes chatbot-server/knowledge.generated.ts: everything Layan (the AI assistant) knows,
// as one text the model reads in full on every reply (cached, see chatbot-server/handler.ts).
// Same sources as the on-device bot (knowledge.mjs): the FAQ, src/content/*.ts and the built
// Arabic pages (out/, from `npm run build`), plus the sales team's own answers (answers.json).
// Run with `npm run chatbot:kb` after content changes.
import { readFileSync, writeFileSync } from "node:fs";
import { collectDocs } from "./knowledge.mjs";

const here = (p) => new URL(p, import.meta.url);
const label = (q) => (q.includes("؟") ? q.split("؟")[0] + "؟" : q);
const answers = JSON.parse(readFileSync(here("answers.json"), "utf8"));

const docs = await collectDocs();
const faq = docs.filter((d) => d.kind === "faq");
const items = docs.filter((d) => d.kind === "item");
const pages = docs.filter((d) => d.kind === "page");

const out = [];
out.push("# أجوبة معتمدة من فريق المبيعات (استخدمها كما هي في المعنى)");
for (const [q, list] of Object.entries(answers)) out.push(`س: ${q}\nج: ${list[0]}`);

out.push("\n# الأسئلة الشائعة ومحتوى الموقع");
for (const d of faq) out.push(`[${d.title} — ${d.url}]\nس: ${label(d.q)}\nج: ${d.text}`);

out.push("\n# تفاصيل (خدمات، مرافق، فريق، مخطط)");
const seen = new Set();
for (const d of items) {
  if (seen.has(d.text)) continue;
  seen.add(d.text);
  out.push(`[${d.title} — ${d.url}] ${d.text}`);
}

out.push("\n# نصوص صفحات الموقع");
let page = "";
for (const d of pages) {
  if (d.url !== page) {
    out.push(`\n## ${d.title} — ${d.url}`);
    page = d.url;
  }
  out.push(d.text);
}

const text = out.join("\n");
writeFileSync(
  here("../chatbot-server/knowledge.generated.ts"),
  `// Generated by chatbot-poc/build-ai-knowledge.mjs (npm run chatbot:kb). Do not edit by hand.\nexport const knowledge = ${JSON.stringify(text)};\n`,
);
console.log(`knowledge: ${text.length} chars (${faq.length} faq, ${seen.size} items, ${pages.length} passages)`);
