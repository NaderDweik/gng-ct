/** Nonsense: only symbols/emoji/digits, one repeated letter, or a random Latin string. */
export function isNoise(text) {
  const t = text.trim();
  if (!t) return true;
  if (!/[\p{L}]/u.test(t)) return true; // emoji / numbers / punctuation only
  if (/^(.)\1{2,}$/u.test(t.replace(/\s/g, ""))) return true; // "ههههه" is handled earlier; "ممممم", "....."
  if (/^[a-z]{5,}$/i.test(t) && !/[aeiouy]/i.test(t)) return true; // "sdfghj"
  // Keyboard mashing: "asdfgh", "qwerty", "jkjkjk".
  if (/^[a-z]{4,}$/i.test(t) && /asdf|sdfg|dfgh|fghj|ghjk|hjkl|qwer|wert|erty|rtyu|tyui|yuio|uiop|zxcv|xcvb|cvbn|vbnm|(\w\w)\1\1/i.test(t)) return true;
  return false;
}

/** Replies to emoji-only messages, by the emoji's mood. */
export function emojiReply(text) {
  if (/[👍👌✅💯🙏]/u.test(text)) return ["👍😊", "بتحب أحكيلك عن إشي بخص الكمباوند؟"];
  if (/[❤️🤍💚💙😍🥰😘]/u.test(text)) return ["🤍😊", "شو حابب تعرف عن روح العطاء؟"];
  if (/[😂🤣😅😄😁]/u.test(text)) return ["😄", "كيف بقدر أساعدك؟"];
  if (/[😢😭😞😔💔]/u.test(text)) return ["سلامتك 🤍", "إذا في إشي بقدر أساعدك فيه، أنا هون."];
  if (/[😡🤬👎]/u.test(text)) return ["سامحني إذا في إشي ضايقك 🙏", "احكيلي شو صار وبحاول أساعدك."];
  return null;
}
